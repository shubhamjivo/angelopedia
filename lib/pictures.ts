const bySlug = new Map(NEWS_IN_PICTURES.map((album) => [album.slug, album]));

export function getPicture(slug: string) {
  return bySlug.get(slug);
}

export const PICTURES_HREF = "/news/in-pictures";

export function picturePath(album: { slug: string }) {
  return `/News-In-Picture/${album.slug}`;
}

export function otherPictures(slug: string, count = 4) {
  const start = NEWS_IN_PICTURES.findIndex((album) => album.slug === slug);
  if (start < 0) return NEWS_IN_PICTURES.slice(0, count);
  const rest = [
    ...NEWS_IN_PICTURES.slice(start + 1),
    ...NEWS_IN_PICTURES.slice(0, start),
  ];
  return rest.slice(0, count);
}

